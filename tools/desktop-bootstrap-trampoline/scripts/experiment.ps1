# P5.8.0 Desktop bootstrap trampoline experiment driver.
#
#   -Phase A  standalone trampoline (no Desktop restart)
#   -Phase B  cold start with CODEX_CLI_PATH set, then wait for one existing-conversation activation
#   -Phase C  transparency checks against the running boot
#   -Phase D  rollback: remove CODEX_CLI_PATH and verify Desktop starts its own core
#   -Phase status  read-only snapshot
#
# Phases B and D restart Desktop and therefore end any Codex session hosted by it:
# run them from a normal PowerShell window, never from inside the Codex app.
[CmdletBinding()]
param(
  [ValidateSet('A','B','C','D','status')]
  [string]$Phase = 'A',
  [int]$WaitSeconds = 180
)

$ErrorActionPreference = 'Stop'
$toolRoot = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$repoRoot = Split-Path -Parent (Split-Path -Parent $toolRoot)
$trampoline = Join-Path $toolRoot 'DesktopBootstrapTrampoline.exe'
$configPath = Join-Path $toolRoot 'trampoline.config.ini'
$productionConfig = Join-Path $repoRoot 'config.production.json'
$evidence = Join-Path $repoRoot '.review\p5.8-bootstrap'
$logs = Join-Path $evidence 'logs'
$logPath = Join-Path $logs 'trampoline.jsonl'
$statePath = Join-Path $evidence 'rollback-state.json'
$aumid = 'OpenAI.Codex_2p2nqsd0c76g0!App'
$killNames = @('ChatGPT','codex','codex-code-mode-host')

New-Item -ItemType Directory -Force -Path $logs | Out-Null

function Send-EnvironmentChanged {
  if (-not ('P58.Native' -as [type])) {
    Add-Type -Namespace P58 -Name Native -MemberDefinition @'
[DllImport("user32.dll", SetLastError = true, CharSet = CharSet.Auto)]
public static extern IntPtr SendMessageTimeout(IntPtr hWnd, uint Msg, IntPtr wParam, string lParam, uint fuFlags, uint uTimeout, out IntPtr lpdwResult);
'@
  }
  $result = [IntPtr]::Zero
  [P58.Native]::SendMessageTimeout([IntPtr]0xffff, 0x001A, [IntPtr]::Zero, 'Environment', 2, 5000, [ref]$result) | Out-Null
}

function Get-UserCliPath { return [Environment]::GetEnvironmentVariable('CODEX_CLI_PATH','User') }

function Set-UserCliPath([string]$Value) {
  if ([string]::IsNullOrEmpty($Value)) {
    Remove-ItemProperty -Path 'HKCU:\Environment' -Name 'CODEX_CLI_PATH' -ErrorAction SilentlyContinue
  } else {
    [Environment]::SetEnvironmentVariable('CODEX_CLI_PATH', $Value, 'User')
  }
  Send-EnvironmentChanged
}

function Read-Entries {
  if (-not (Test-Path -LiteralPath $logPath)) { return @() }
  return @(Get-Content -LiteralPath $logPath | Where-Object { $_.Trim() -ne '' } | ForEach-Object { $_ | ConvertFrom-Json })
}

function Write-Evidence([string]$Name, $Value) {
  $Value | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $evidence $Name) -Encoding UTF8
}

function Test-DesktopProcesses { @(Get-Process -Name $killNames -ErrorAction SilentlyContinue) }

function Stop-Desktop {
  Get-Process -Name 'ChatGPT' -ErrorAction SilentlyContinue | ForEach-Object { try { $_.CloseMainWindow() | Out-Null } catch { } }
  Start-Sleep -Seconds 3
  foreach ($name in $killNames) { Get-Process -Name $name -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue }
  $deadline = (Get-Date).AddSeconds(45)
  while ((Get-Date) -lt $deadline) {
    if (-not (Test-DesktopProcesses)) { return $true }
    Start-Sleep -Milliseconds 500
  }
  return $false
}

function Start-Desktop {
  Start-Process -FilePath (Join-Path $env:SystemRoot 'explorer.exe') -ArgumentList "shell:AppsFolder\$aumid"
  $deadline = (Get-Date).AddSeconds(60)
  while ((Get-Date) -lt $deadline) {
    if (Get-Process -Name 'ChatGPT' -ErrorAction SilentlyContinue) { return $true }
    Start-Sleep -Milliseconds 500
  }
  return $false
}

function Get-LauncherSettings {
  if (-not (Test-Path -LiteralPath $productionConfig)) { throw "production config not found: $productionConfig" }
  $config = Get-Content -LiteralPath $productionConfig -Raw | ConvertFrom-Json
  return @{ baseUrl = "http://127.0.0.1:$($config.port)"; token = $config.auth.token }
}

function Invoke-Launcher([string]$Path, $Settings) {
  $headers = @{ authorization = "Bearer $($Settings.token)" }
  $response = Invoke-WebRequest -UseBasicParsing -Uri "$($Settings.baseUrl)$Path" -Headers $headers -TimeoutSec 10
  return ($response.Content | ConvertFrom-Json)
}

function New-TrampolineConfig {
  $settings = Get-LauncherSettings
  $lines = @(
    '# generated by experiment.ps1 - local launcher token, never commit this file',
    "logDir=$logs",
    "baseUrl=$($settings.baseUrl)",
    "authToken=$($settings.token)",
    'handoffEnabled=true',
    'handoffDeadlineSeconds=120',
    'handoffTimeoutSeconds=2',
    'realCodexPath='
  )
  $lines -join "`n" | Set-Content -LiteralPath $configPath -Encoding UTF8
  return $settings
}

function Get-NewestDesktopLog {
  $root = Join-Path $env:LOCALAPPDATA 'Codex\Logs'
  $today = Get-Date -Format 'yyyy\\MM\\dd'
  $files = Get-ChildItem -Path (Join-Path $root $today) -Filter 'codex-desktop-*-t0-*.log' -ErrorAction SilentlyContinue
  if (-not $files) { return $null }
  return ($files | Sort-Object LastWriteTime | Select-Object -Last 1)
}

if ($Phase -eq 'status') {
  $settings = Get-LauncherSettings
  Write-Host "user CODEX_CLI_PATH = '$(Get-UserCliPath)'"
  Write-Host "config present: $(Test-Path -LiteralPath $configPath)"
  try { Write-Host ('desktop-interactive: ' + ((Invoke-Launcher '/launcher/desktop-interactive' $settings) | ConvertTo-Json -Compress)) } catch { Write-Host "desktop-interactive: ERR $($_.Exception.Message)" }
  try { Write-Host ('desktop-sync: ' + ((Invoke-Launcher '/launcher/desktop-sync' $settings) | ConvertTo-Json -Compress)) } catch { Write-Host "desktop-sync: ERR $($_.Exception.Message)" }
  Read-Entries | Select-Object -Last 6 | ForEach-Object { $_ | ConvertTo-Json -Compress } | Write-Host
  exit 0
}

if ($Phase -eq 'A') {
  if (-not (Test-Path -LiteralPath $trampoline)) { throw "trampoline not built: $trampoline" }
  $settings = New-TrampolineConfig
  $before = (Read-Entries).Count
  $versionOutput = & $trampoline --version 2>&1 | Out-String
  $versionExit = $LASTEXITCODE
  $previousErrorAction = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    $unknownOutput = & $trampoline --p58-unknown-flag 2>&1 | Out-String
    $unknownExit = $LASTEXITCODE
  } finally {
    $ErrorActionPreference = $previousErrorAction
  }
  Start-Sleep -Seconds 3
  $entries = Read-Entries | Select-Object -Skip $before
  $launch = $entries | Where-Object { $_.event -eq 'launch' } | Select-Object -First 1
  $exit0 = $entries | Where-Object { $_.event -eq 'exit' } | Select-Object -First 1
  $handoff = $entries | Where-Object { $_.event -like 'handoff_*' } | Select-Object -First 1
  $result = [ordered]@{
    phase = 'A'
    completed_utc = (Get-Date).ToUniversalTime().ToString('o')
    version_exit = $versionExit
    version_output = $versionOutput.Trim()
    unknown_flag_exit = $unknownExit
    unknown_flag_output_head = ($unknownOutput.Trim() -split "`n")[0]
    real_codex_path = $launch.real_codex_path
    real_codex_source = $launch.real_codex_source
    argv = $launch.argv
    child_command_line = ($entries | Where-Object { $_.event -eq 'spawned' } | Select-Object -First 1).child_command_line
    child_exit_code = $exit0.child_exit_code
    pipe_present = $launch.pipe_present
    handoff_event = $handoff.event
    handoff_status = $handoff.http_status
    handoff_body = $handoff.response_body
  }
  $result.pass = ($versionExit -eq 0) -and ($versionOutput -match 'codex-cli') -and ($unknownExit -ne 0) -and ($launch.real_codex_source -eq 'registered_core')
  Write-Evidence 'test-a.json' $result
  $result | ConvertTo-Json -Depth 8 | Write-Host
  if (-not $result.pass) { exit 1 }
  exit 0
}

if ($Phase -eq 'B') {
  if (-not (Test-Path -LiteralPath $trampoline)) { throw "trampoline not built: $trampoline" }
  $settings = New-TrampolineConfig
  $previous = Get-UserCliPath
  $before = (Read-Entries).Count
  $state = [ordered]@{
    phase = 'B'
    started_utc = (Get-Date).ToUniversalTime().ToString('o')
    previous_user_codex_cli_path = $previous
    probe_records_before = $before
  }
  Write-Evidence 'rollback-state.json' $state
  Write-Host "previous CODEX_CLI_PATH = '$previous'; trampoline records = $before"
  if (-not (Stop-Desktop)) { throw 'Desktop processes did not exit' }
  Set-UserCliPath $trampoline
  Write-Host "CODEX_CLI_PATH(user) = '$trampoline'; starting Desktop"
  $state.desktop_started = Start-Desktop
  $deadline = (Get-Date).AddSeconds($WaitSeconds)
  $initialHandoff = $null
  $handoff = $null
  $boot = $null
  while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 3
    $entries = Read-Entries | Select-Object -Skip $before
    $boot = $entries | Where-Object { $_.event -eq 'launch' -and $_.command_line -like '*app-server*' } | Select-Object -First 1
    if ($null -eq $initialHandoff) {
      $initialHandoff = $entries | Where-Object {
        $_.event -eq 'handoff_retry' -and $_.http_status -eq 202 -and $_.response_body -match '"pending":true'
      } | Select-Object -First 1
      if ($boot -and $initialHandoff) {
        Write-Host 'handoff pending; switch one existing Desktop conversation, then leave this process running'
      }
    }
    $handoff = $entries | Where-Object { $_.event -eq 'handoff_accepted' } | Select-Object -First 1
    if ($boot -and $handoff) { break }
  }
  $state.boot_launch = $boot
  $state.initial_handoff = $initialHandoff
  $state.handoff = $handoff
  # The handoff can be accepted a moment before LRM reports it as ready; poll briefly instead of
  # recording a single racy reading.
  $readings = @()
  $readyDeadline = (Get-Date).AddSeconds(30)
  while ((Get-Date) -lt $readyDeadline) {
    try { $reading = Invoke-Launcher '/launcher/desktop-interactive' $settings } catch { $reading = @{ error = $_.Exception.Message } }
    $readings += $reading
    if ($reading.ready -eq $true -and $reading.pipeSource -eq 'handoff') { break }
    Start-Sleep -Seconds 3
  }
  $state.desktop_interactive_readings = $readings
  $state.desktop_interactive = $readings[$readings.Count - 1]
  try { $state.desktop_sync = Invoke-Launcher '/launcher/desktop-sync' $settings } catch { $state.desktop_sync = @{ error = $_.Exception.Message } }
  $state.completed_utc = (Get-Date).ToUniversalTime().ToString('o')
  $state.pass = ($null -ne $boot) -and ($null -ne $initialHandoff) -and ($handoff.event -eq 'handoff_accepted') -and
    ($state.desktop_interactive.ready -eq $true) -and ($state.desktop_interactive.pipeSource -eq 'handoff') -and
    ($state.desktop_sync.connected -eq $true) -and ($null -ne $state.desktop_sync.ownerClientId)
  Write-Evidence 'test-b.json' $state
  $state | ConvertTo-Json -Depth 8 | Write-Host
  if (-not $state.pass) { exit 1 }
  exit 0
}

if ($Phase -eq 'C') {
  $settings = New-TrampolineConfig
  $entries = Read-Entries
  $boot = $entries | Where-Object { $_.event -eq 'launch' -and $_.command_line -like '*app-server*' } | Select-Object -Last 1
  $trampolineProcess = $null
  if ($boot) { $trampolineProcess = Get-Process -Id $boot.probe_pid -ErrorAction SilentlyContinue }
  $appServer = $null
  if ($boot) {
    $appServer = Get-CimInstance Win32_Process -Filter "ParentProcessId = $($boot.probe_pid) AND Name = 'codex.exe'" -ErrorAction SilentlyContinue
  }
  $desktopLog = Get-NewestDesktopLog
  $desktopEvidence = @()
  if ($desktopLog) {
    $desktopEvidence = (Get-Content -LiteralPath $desktopLog.FullName | Select-String -Pattern 'component=codex consumer=app-server|reported app-server version' | Select-Object -First 4).Line
  }
  $failures = @($entries | Where-Object { $_.event -in @('resolution_failed','spawn_failed','recursion_detected') })
  $result = [ordered]@{
    phase = 'C'
    completed_utc = (Get-Date).ToUniversalTime().ToString('o')
    boot_launch = $boot
    trampoline_process_alive = ($null -ne $trampolineProcess)
    app_server = $appServer
    desktop_log = $desktopLog.FullName
    desktop_evidence = $desktopEvidence
    failure_records = $failures
  }
  try { $result.desktop_sync = Invoke-Launcher '/launcher/desktop-sync' $settings } catch { $result.desktop_sync = @{ error = $_.Exception.Message } }
  $result.pass = ($null -ne $boot) -and ($null -ne $trampolineProcess) -and ($null -ne $appServer) -and ($failures.Count -eq 0)
  Write-Evidence 'test-c.json' $result
  $result | ConvertTo-Json -Depth 8 | Write-Host
  if (-not $result.pass) { exit 1 }
  exit 0
}

if ($Phase -eq 'D') {
  $previous = $null
  if (Test-Path -LiteralPath $statePath) { $previous = (Get-Content -LiteralPath $statePath -Raw | ConvertFrom-Json).previous_user_codex_cli_path }
  $before = (Read-Entries).Count
  if (-not (Stop-Desktop)) { throw 'Desktop processes did not exit' }
  Set-UserCliPath $previous
  Write-Host "restored CODEX_CLI_PATH = '$previous'; starting Desktop"
  $started = Start-Desktop
  Start-Sleep -Seconds 45
  $after = (Read-Entries).Count
  $desktopLog = Get-NewestDesktopLog
  $desktopEvidence = @()
  if ($desktopLog) {
    $desktopEvidence = (Get-Content -LiteralPath $desktopLog.FullName | Select-String -Pattern 'component=codex consumer=app-server' | Select-Object -First 2).Line
  }
  $result = [ordered]@{
    phase = 'D'
    completed_utc = (Get-Date).ToUniversalTime().ToString('o')
    restored_value = $previous
    user_codex_cli_path_now = Get-UserCliPath
    desktop_started = $started
    probe_records_before = $before
    probe_records_after = $after
    probe_records_added = $after - $before
    desktop_log = $desktopLog.FullName
    desktop_evidence = $desktopEvidence
    trampoline_processes = @(Get-Process -Name 'DesktopBootstrapTrampoline' -ErrorAction SilentlyContinue | Select-Object Id)
  }
  $usedBundledCore = [bool]($desktopEvidence -match 'source=copied|source=bundled-or-dev|OpenAI\\Codex\\bin')
  $result.pass = ($result.probe_records_added -eq 0) -and ($result.trampoline_processes.Count -eq 0) -and $usedBundledCore
  Write-Evidence 'test-d.json' $result
  $result | ConvertTo-Json -Depth 8 | Write-Host
  if (-not $result.pass) { exit 1 }
  exit 0
}
